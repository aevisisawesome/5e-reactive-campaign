"""Writes assets/session-links.js: for each place, the session walkthrough sections about it.

Run from anywhere, after rebuilding a session page:
    python build_session_links.py

A section counts as "about" a place when its heading names it, the page marks it
as covering it (data-entity-local), or its "When / where" line names it. Places
with no such section get up to three sections that only mention them.
"""
import io, json, os, re
from html.parser import HTMLParser

GUIDE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
# newest first: that is the order the links are shown in
PAGES = [("10-session-three.html", "Session 3"), ("07-session-two.html", "Session 2"),
         ("03-session-one.html", "Session 1")]
HEADS = ("h1", "h2", "h3", "h4")


class Sections(HTMLParser):
    """Split a page into sections: one per heading that has an id (or sits in a <section id>)."""

    def __init__(self):
        super().__init__()
        self.out, self.cur, self.head, self.buf = [], None, None, []
        self.part = ""

    def handle_starttag(self, tag, attrs):
        a = dict(attrs)
        if tag in HEADS:
            self.head = [tag, a.get("id"), a.get("data-entity-local", ""), []]
        elif tag in ("p", "li", "tr", "div", "br") and self.cur:
            self.cur["text"].append("\n")

    def handle_endtag(self, tag):
        if self.head and tag == self.head[0]:
            level, hid, local, words = self.head
            title = " ".join("".join(words).split())
            self.head = None
            if level == "h1":
                self.part = title
            if hid:
                self.cur = {"id": hid, "title": title, "local": local.split(), "text": [], "level": level,
                            "part": self.part}
                self.out.append(self.cur)
            elif self.cur:
                self.cur["text"].append("\n" + title + "\n")

    def handle_data(self, data):
        if self.head:
            self.head[3].append(data)
        elif self.cur:
            self.cur["text"].append(data)


def entities():
    src = io.open(os.path.join(GUIDE, "assets", "entities.js"), encoding="utf-8").read()
    for m in re.finditer(r'id: "([^"]+)",\s*name: "([^"]+)",\s*aliases: \[([^\]]*)\],\s*type: "([^"]+)"', src):
        eid, name, aliases, kind = m.groups()
        if kind in ("location", "zone", "sector") or eid.startswith("waystone-"):
            yield eid, [name] + re.findall(r'"([^"]+)"', aliases)


def patterns(eid, names):
    out = []
    code = re.match(r"([gzs]\d+)-", eid)
    if code:
        out.append(r"\b" + code.group(1).upper() + r"\b")
    for n in names:
        n = re.sub(r"^[Tt]he\s+", "", n)
        if len(n) >= 4:
            # a capitalised name stays case-sensitive: "the Cut" is not "a cut"
            out.append(r"\b" + re.escape(n) + r"\b")
    return [re.compile(p) for p in out]


def main():
    pages = []
    for fname, label in PAGES:
        p = Sections()
        p.feed(io.open(os.path.join(GUIDE, fname), encoding="utf-8").read())
        pages.append((fname, label, p.out))

    result = {}
    for eid, names in entities():
        pats = patterns(eid, names)
        strong, weak = [], []
        for fname, label, secs in pages:
            for s in secs:
                if s["level"] == "h1" or re.search(r"Appendix|Materials|Self-check|Changes to", s["part"] + s["title"]):
                    continue
                text = "".join(s["text"])
                where = " ".join(re.findall(r"When / where:[^\n]*(?:\n(?!\n)[^\n]*)?", text))
                hit = lambda t: any(p.search(t) for p in pats)
                item = {"p": fname, "s": label, "a": s["id"], "t": s["title"]}
                if eid in s["local"] or hit(s["title"]) or hit(where):
                    strong.append(item)
                else:
                    n = sum(len(p.findall(text)) for p in pats)
                    if n:
                        weak.append((n, item))
        rows = [dict(i, k=1) for i in strong]
        have = {r["p"] for r in rows}
        # for a session with no section of its own, offer its best two mentions
        for fname, _ in PAGES:
            if fname not in have:
                best = sorted((w for w in weak if w[1]["p"] == fname), key=lambda w: -w[0])[:2]
                rows += [dict(i, k=0) for _, i in best]
        if rows:
            order = {f: n for n, (f, _) in enumerate(PAGES)}
            rows.sort(key=lambda r: (order[r["p"]], -r["k"]))
            result[eid] = rows

    out = os.path.join(GUIDE, "assets", "session-links.js")
    with io.open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("/* Generated by tools/build_session_links.py. Do not edit by hand. */\n")
        f.write("window.SESSION_LINKS = " + json.dumps(result, ensure_ascii=False, separators=(",", ":")) + ";\n")
    print("places with links:", len(result))
    return result


if __name__ == "__main__":
    main()
